#include "interrupt.h"
#include "bsp_encoder.h"
#include "ti_msp_dl_config.h"

/*
*********************************************************************************************************
*   全局变量
*********************************************************************************************************
*/
static volatile uint32_t s_ticks = 0U;     /* 系统毫秒节拍，单位ms，32位约49天回绕 */

/*
*********************************************************************************************************
*   函 数 名: SysTick_Handler
*   功能说明: SysTick中断服务函数，1ms进入一次
*   形    参: 无
*   返 回 值: 无
*********************************************************************************************************
*/
void SysTick_Handler(void)
{
    s_ticks++;
}

/*
*********************************************************************************************************
*   函 数 名: GROUP1_IRQHandler
*   功能说明: GPIO组中断服务函数，统一转发到各BSP中断回调
*   形    参: 无
*   返 回 值: 无
*********************************************************************************************************
*/
void GROUP1_IRQHandler(void)
{
    BSP_Encoder_GPIOGroupIRQHandler();
}

/*
*********************************************************************************************************
*   函 数 名: Get_Tick
*   功能说明: 获取系统运行时间
*   形    参: 无
*   返 回 值: 当前tick，单位ms
*********************************************************************************************************
*/
uint32_t Get_Tick(void)
{
    return s_ticks;
}
