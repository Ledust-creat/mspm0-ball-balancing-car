#include "ti_msp_dl_config.h"
#include "delay.h"
/*
*********************************************************************************************************
*   函 数 名: delay_us
*   功能说明: 粗略微秒延时
*   形    参: us — 延时时间，单位us
*   返 回 值: 无
*********************************************************************************************************
*/
void delay_us(uint16_t us)
{
    for (int i = 0; i < 100; i++) {
         delay_cycles(800000*us);
    }
   
}
/*
*********************************************************************************************************
*   函 数 名: delay_ms
*   功能说明: 粗略毫秒延时
*   形    参: ms — 延时时间，单位ms
*   返 回 值: 无
*********************************************************************************************************
*/
void delay_ms(uint16_t ms)
{
    for (int i = 0; i < 100; i++) {
         delay_cycles(800000/1000*ms);
    }
   
}

