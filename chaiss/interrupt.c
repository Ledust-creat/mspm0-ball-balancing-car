#include "interrupt.h"
#include "bsp_encoder.h"
#include "ti_msp_dl_config.h"

/*
*********************************************************************************************************
*   全局变量
*********************************************************************************************************
*/
static volatile uint64_t s_ticks = 0;      /* 系统毫秒节拍 */

/*
*********************************************************************************************************
*   函 数 名: SysTick_Handler
*   功能说明: SysTick中断服务函数，1ms进入一次
*   形    参: 无
*   返 回 值: 无
*********************************************************************************************************
*/
void SysTick_Handler(void)
{
    s_ticks++;
}

/*
*********************************************************************************************************
*   函 数 名: GROUP1_IRQHandler
*   功能说明: GPIO组1中断服务函数，统一转发到各BSP中断回调
*   形    参: 无
*   返 回 值: 无
*********************************************************************************************************
*/
void GROUP1_IRQHandler(void)
{
    BSP_Encoder_GPIOGroupIRQHandler();

    /*
     * 后续如果增加按键等GPIO组1中断，在这里继续转发：
     * BSP_Key_GPIOGroupIRQHandler();
     */
}

/*
*********************************************************************************************************
*   函 数 名: Get_Tick
*   功能说明: 获取系统运行时间
*   形    参: 无
*   返 回 值: 当前tick，单位ms
*********************************************************************************************************
*/
uint64_t Get_Tick(void)
{
    return s_ticks;
}
