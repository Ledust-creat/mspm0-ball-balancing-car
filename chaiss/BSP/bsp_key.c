/*
*********************************************************************************************************
*   函 数 名: BSP_Key_IsSelectPressed
*   功能说明: 读取SELECT按键原始按下状态
*   形    参: 无
*   返 回 值: true按下，false松开
*********************************************************************************************************
*/
bool BSP_Key_IsSelectPressed(void)
{
    return (DL_GPIO_readPins(KEY_SELECT_PORT, KEY_SELECT_PIN) == 0U);
}

